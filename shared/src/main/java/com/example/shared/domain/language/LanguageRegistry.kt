    private val byCode: Map<String, Language> = ALL.associateBy { it.code }

    fun byCode(code: String): Language? = byCode[code]

    val DEFAULT: Language get() = byCode("en")!!

    /**
     * [java.util.Locale.getLanguage] returns the legacy "iw" for Hebrew, not
     * the modern "he" this registry keys on -- same special case the old
     * SolutionLanguageOption.fromLocale carried.
     */
    fun fromLocale(locale: java.util.Locale): Language? {
        val language = locale.language
        if (language == "iw" || language == "he") return byCode("he")
        return byCode(language)
    }

    /**
     * Default "quick list" the language picker shows before a user has
     * picked enough languages themselves to build a real recent-languages
     * list -- English first, then the primary language of each of this
     * app's top install-audience countries, ordered by install count (Play
     * Console "Installed audience" chart, snapshot taken 2026-09-28):
     * Israel, Kenya, Russia, Turkiye, Nigeria, Ethiopia, India, Germany,
     * Belarus, Kazakhstan. One representative language per country (Kenya:
     * Swahili over English, already listed; Nigeria: Hausa, its most widely
     * spoken indigenous language, over Yoruba/Igbo). A one-time seed, not
     * live data -- nothing here re-fetches install stats.
     */
    val INITIAL_QUICK_LIST: List<Language> = listOf(
        "en", "he", "sw", "ru", "tr", "ha", "am", "hi", "de", "be", "kk",
    ).map { byCode(it)!! }
